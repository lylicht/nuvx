export type VyralLanguage = 'en' | 'fa';

/** Match full BCP-47 values such as fa-IR and fa-Arab, independent of casing. */
export function resolveVyralLanguage(languages: readonly string[] | undefined): VyralLanguage {
  const preferredSupportedLanguage = languages
    ?.map((tag) => tag.toLowerCase().split(/[-_]/, 1)[0])
    .find((language) => language === 'fa' || language === 'en');
  return preferredSupportedLanguage === 'fa' ? 'fa' : 'en';
}

export function translationFor(language: VyralLanguage, key: string): string {
  return language === 'fa' ? (faTranslations[key] ?? key) : key;
}
